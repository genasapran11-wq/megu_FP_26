def same(a, b):
    if isinstance(a, bool) or isinstance(b, bool):
        return type(a) == type(b) and a == b
    if isinstance(a, (int, float)) and isinstance(b, (int, float)):
        return abs(a - b) < 1e-6
    if isinstance(a, list) and isinstance(b, list):
        return len(a) == len(b) and all(same(x, y) for x, y in zip(a, b))
    return a == b


def nice(value):
    if isinstance(value, float):
        value = round(value, 6)
    if isinstance(value, list):
        return "[" + ", ".join(nice(v) for v in value) + "]"
    return repr(value)


def main():
    name = sys.argv[1] if len(sys.argv) > 1 else "practical"
    name = name[:-3] if name.endswith(".py") else name
    try:
        with contextlib.redirect_stdout(io.StringIO()):
            module = importlib.import_module(name)
    except SyntaxError as error:
        print(f"[!!] У файлі {name}.py синтаксична помилка, рядок {error.lineno}: {error.msg}")
        print("     Виправте її й запустіть перевірку ще раз.")
        return
    except Exception as error:
        print(f"[!!] Файл {name}.py не запускається: {type(error).__name__}: {error}")
        return

    card = getattr(module, "CARD", 0)
    if card not in EXPECTED:
        print(f"[!!] Впишіть номер своєї картки на початку файла, наприклад CARD = 7 (номер від 1 до {len(EXPECTED)}).")
        return
    print(f"Картка {card}. Перевіряю файл {name}.py")
    print()

    for func_name, label in FUNCTIONS:
        func = getattr(module, func_name, None)
        if func is None or not callable(func):
            extra = " (необов'язково)" if func_name in OPTIONAL else ""
            print(f"[--] {label} {func_name}: ще не написано{extra}")
            continue
        problems = []
        for case_name, args, expected in EXPECTED[card]:
            if case_name != func_name:
                continue
            call = f"{func_name}({', '.join(nice(a) for a in args)})"
            given = copy.deepcopy(list(args))
            before = copy.deepcopy(given)
            try:
                with contextlib.redirect_stdout(io.StringIO()) as printed:
                    result = func(*given)
            except Exception as error:
                hint = ""
                if isinstance(error, TypeError) and "argument" in str(error):
                    hint = " (не та кількість параметрів: порівняйте з викликом)"
                problems.append(f"{call} -> помилка {type(error).__name__}: {error}{hint}")
                continue
            if result is None and expected is not None:
                hint = " (функція щось друкує, але нічого не повертає: потрібен return)" if printed.getvalue() else " (немає return?)"
                problems.append(f"{call} -> None, очікували {nice(expected)}{hint}")
            elif not same(result, expected):
                problems.append(f"{call} -> {nice(result)}, очікували {nice(expected)}")
            if func_name in NO_MUTATION and given != before:
                problems.append(f"{call} ЗМІНИЛА вхідний список: було {nice(before[0])}, стало {nice(given[0])}. "
                                "Поверніть новий список замість зміни старого.")
        if problems:
            print(f"[!!] {label} {func_name}:")
            for problem in problems:
                print("     " + problem)
        else:
            print(f"[OK] {label} {func_name}")
            needed = COMPOSE.get(func_name, [])
            try:
                source = inspect.getsource(func)
            except (OSError, TypeError):
                source = ""
            missing = [n for n in needed if n + "(" not in source]
            if source and missing:
                print(f"     [i] не використано {', '.join(missing)} — на захисті вас спитають чому")
    print()
    print("Пам'ятайте: бали за код зараховуються після онлайн-захисту — будьте готові пояснити кожен рядок")
    print("і змінити код наживо з демонстрацією екрана.")


main()
